def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def apply_perspective_angle(
    image: np.ndarray,
    *,
    angle: int,
    sample_id: str,
    seed: int = ROBUSTNESS_SEED,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Apply the formal deterministic projective geometry at one exact angle."""

    _require(int(angle) in ANGLES, f"unsupported perspective angle: {angle}")
    _require(image is not None and image.size > 0, "perspective input is empty")
    if int(angle) == 0:
        return np.ascontiguousarray(image.copy()), {
            "angle": 0,
            "axis": "none",
            "sign": 0,
            "seed": int(seed),
            "valid_support_fraction": 1.0,
        }

    height, width = image.shape[:2]
    axis, sign = robustness_degradations._sample_orientation(
        str(sample_id), int(seed)
    )
    destination = robustness_degradations._projected_corners(
        width,
        height,
        float(angle),
        axis,
        sign,
    )
    source = np.asarray(
        [
            [0.0, 0.0],
            [width - 1.0, 0.0],
            [width - 1.0, height - 1.0],
            [0.0, height - 1.0],
        ],
        dtype=np.float32,
    )
    homography = cv2.getPerspectiveTransform(source, destination)
    warped = cv2.warpPerspective(
        image,
        homography,
        (width, height),
        flags=cv2.INTER_LINEAR,
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=robustness_degradations._border_median(image),
    )
    source_support = np.ones((height, width), dtype=np.float32)
    warped_support = cv2.warpPerspective(
        source_support,
        homography,
        (width, height),
        flags=cv2.INTER_LINEAR,
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=0.0,
    )
    valid_support_fraction = float(
        np.mean(np.clip(warped_support, 0.0, 1.0), dtype=np.float64)
    )
    _require(
        math.isfinite(valid_support_fraction)
        and 0.0 < valid_support_fraction <= 1.0,
        "projected valid support fraction is invalid",
    )
    return np.ascontiguousarray(warped), {
        "angle": int(angle),
        "axis": axis,
        "sign": int(sign),
        "seed": int(seed),
        "valid_support_fraction": valid_support_fraction,
    }


class PerspectiveAngleDataset(Dataset[dict[str, Any]]):
    """Materialize one exact angle over the invariant formal SyncG roster."""

    def __init__(
        self,
        rows: Sequence[ManifestRow],
        targets: Mapping[str, tuple[float, str]],
        *,
        angle: int,
    ) -> None:
        self.rows = tuple(rows)
        self.targets = targets
        self.angle = int(angle)
        _require(bool(self.rows), "perspective dataset is empty")
        _require(self.angle in ANGLES, "perspective angle is not prespecified")
        _require(
            {row.sample_id for row in self.rows} == set(targets),
            "perspective manifest and target rosters differ",
        )

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, index: int) -> dict[str, Any]:
        source = self.rows[int(index)]
        _payload, clean = load_canonical_roi(source)
        degraded, perspective = apply_perspective_angle(
            clean,
            angle=self.angle,
            sample_id=source.sample_id,
        )
        decision = normalize_support_aware_roi_v2(degraded)
        height, width = degraded.shape[:2]

        decision_active = bool(decision.applied)
        fallback_reason = decision.fallback_reason
        raw_mask = decision.valid_support_mask
        support: np.ndarray
        normalized = decision.image
        if raw_mask is None:
            decision_active = False
            support = np.ones((IMAGE_SIZE, IMAGE_SIZE), dtype=np.float32)
            fallback_reason = fallback_reason or "support_mask_missing"
        else:
            support = cv2.resize(
                np.asarray(raw_mask, dtype=np.float32),
                (IMAGE_SIZE, IMAGE_SIZE),
                interpolation=cv2.INTER_AREA,
            )
            support = np.clip(support, 0.0, 1.0).astype(np.float32)
            if not np.isfinite(support).all() or float(support.sum()) <= 0.0:
                decision_active = False
                support = np.ones((IMAGE_SIZE, IMAGE_SIZE), dtype=np.float32)
                fallback_reason = "resized_support_mask_invalid"

        if decision_active:
            homography = _normalized_raw_to_sarn_homography(
                decision,
                height=height,
                width=width,
            )
        else:
            homography = np.eye(3, dtype=np.float32)

        active = decision_active and self.angle > 0
        if self.angle == 0:
            fallback_reason = "angle_zero_identity"
        elif active:
            fallback_reason = None

        # This reported diagnostic is the actual fraction of the projectively
        # warped source plane that remains in the canvas.  It is deliberately
        # separate from ``support``, whose all-ones fallback is the effective
        # model-input mask and would otherwise hide high-angle support loss.
        valid_support_fraction = float(perspective["valid_support_fraction"])
        _require(
            math.isfinite(valid_support_fraction)
            and 0.0 < valid_support_fraction <= 1.0,
            "valid support fraction is invalid",
        )
        target, scene = self.targets[source.sample_id]
        return {
            "sample_id": source.sample_id,
            "scene_stem": scene,
            "angle": torch.tensor(self.angle, dtype=torch.int16),
            "perspective_axis": perspective["axis"],
            "perspective_sign": torch.tensor(
                int(perspective["sign"]), dtype=torch.int8
            ),
            "original_view": normalized_rgb_tensor(
                direct_resize_whole_roi(degraded, size=IMAGE_SIZE)
            ),
            "sarn_view": normalized_rgb_tensor(
                direct_resize_whole_roi(normalized, size=IMAGE_SIZE)
            ),
            "sarn_support_mask": torch.from_numpy(
                np.ascontiguousarray(support[None], dtype=np.float32)
            ),
            "sarn_active": torch.tensor(active, dtype=torch.bool),
            "fallback": torch.tensor(not active, dtype=torch.bool),
            "fallback_reason": fallback_reason or "",
            "valid_support_fraction": torch.tensor(
                valid_support_fraction, dtype=torch.float32
            ),
            "raw_to_sarn_homography": torch.from_numpy(
                np.ascontiguousarray(homography, dtype=np.float32)
            ),
            "target": torch.tensor(float(target), dtype=torch.float32),
        }


def _load_geoprr(
    path: Path,
    *,
    expected_variant: str,
    expected_seed: int,
    device: torch.device,
) -> tuple[torch.nn.Module, dict[str, Any]]:
    model, metadata = load_unified_pointer_reader_checkpoint(path, device=device)
    _require(metadata["variant"] == expected_variant, "GeoPRR variant differs")
    _require(int(metadata["seed"]) == int(expected_seed), "GeoPRR seed differs")
    model.eval()
    return model, metadata


def _load_raw_efficientnet(
    path: Path,
    *,
    expected_seed: int,
    device: torch.device,
) -> tuple[torch.nn.Module, dict[str, Any]]:
    source = Path(path).resolve()
    payload = torch.load(source, map_location="cpu", weights_only=False)
    _require(isinstance(payload, Mapping), "raw EfficientNet checkpoint is malformed")
    _require(payload.get("protocol") == LIGHTWEIGHT_PROTOCOL, "raw protocol differs")
    _require(payload.get("architecture") == "efficientnet_b0", "raw architecture differs")
    _require(int(payload["seed"]) == int(expected_seed), "raw seed differs")
    _require(
        payload.get("pretrained_weights")
        == BACKBONE_SPECS["efficientnet_b0"].weights_name,
        "raw initialization metadata differs",
    )
    state = payload.get("model_state")
    _require(isinstance(state, Mapping), "raw model state is missing")
    model = LightweightProgressRegressor(
        "efficientnet_b0", imagenet_pretrained=False
    )
    model.load_state_dict(state, strict=True)
    model = model.to(device).eval()
    for parameter in model.parameters():
        parameter.requires_grad_(False)
    return model, {
        "checkpoint": str(source),
        "protocol": LIGHTWEIGHT_PROTOCOL,
        "architecture": "efficientnet_b0",
        "seed": int(payload["seed"]),
        "checkpoint_selection": payload.get("checkpoint_selection"),
    }


class _CompressedCsvWriter:
    def __init__(self, path: Path) -> None:
        self.path = Path(path).resolve()
        self.path.parent.mkdir(parents=True, exist_ok=True)
        raw = self.path.open("wb")
        compressed = gzip.GzipFile(
            filename="", mode="wb", compresslevel=9, fileobj=raw, mtime=0
        )
        self._raw = raw
        self._compressed = compressed
        self._text = io.TextIOWrapper(compressed, encoding="utf-8", newline="")
        self.writer = csv.DictWriter(
            self._text,
            fieldnames=OUTPUT_FIELDS,
            lineterminator="\n",
        )
        self.writer.writeheader()
        self.rows = 0

    def write(self, row: Mapping[str, Any]) -> None:
        self.writer.writerow(dict(row))
        self.rows += 1

    def close(self) -> None:
        self._text.flush()
        self._text.close()

    def __enter__(self) -> "_CompressedCsvWriter":
        return self

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> None:
        self.close()


def evaluate_perspective_scan(
    *,
    geoprr_root: Path,
    raw_root: Path,
    manifest_path: Path,
    reference_path: Path,
    output_path: Path,
    metadata_path: Path,
    device_name: str,
    workers: int,
    batch_size: int,
    use_amp: bool,
) -> dict[str, Any]:
    """Evaluate all three models, seeds, and angles on one paired pixel stream."""

    _require(workers >= 0 and batch_size >= 1, "perspective loader sizes are invalid")
    output = Path(output_path).resolve()
    metadata_output = Path(metadata_path).resolve()
    _require(not output.exists(), f"perspective output already exists: {output}")
    _require(
        not metadata_output.exists(),
        f"perspective metadata already exists: {metadata_output}",
    )
    device = torch.device(device_name)
    _require(device.type in {"cpu", "cuda"}, "device must be CPU or CUDA")
    if device.type == "cuda":
        _require(torch.cuda.is_available(), "CUDA is unavailable")
    torch.manual_seed(EVALUATION_SEED)
    if device.type == "cuda":
        torch.cuda.manual_seed_all(EVALUATION_SEED)
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True

    _reference, _reference_by_key, ordered_ids, targets = _load_reference(
        reference_path
    )
    _require(len(ordered_ids) == 1558, "formal SyncG sample count differs")
    _require(
        len({scene for _target, scene in targets.values()}) == 14,
        "formal SyncG scene count differs",
    )
    manifest_rows = load_manifest(manifest_path)
    by_id = {row.sample_id: row for row in manifest_rows}
    _require(len(by_id) == len(manifest_rows), "manifest sample IDs repeat")
    _require(set(by_id) == set(ordered_ids), "manifest and reference rosters differ")
    ordered_manifest = tuple(by_id[sample_id] for sample_id in ordered_ids)

    models: dict[int, dict[str, torch.nn.Module]] = {}
    model_metadata: dict[str, Any] = {}
    for seed in SEEDS:
        full, full_metadata = _load_geoprr(
            Path(geoprr_root) / f"seed_{seed}/full/ema.pt",
            expected_variant=FULL,
            expected_seed=seed,
            device=device,
        )
        no_geometry, no_geometry_metadata = _load_geoprr(
            Path(geoprr_root) / f"seed_{seed}/no_geometry_fusion/ema.pt",
            expected_variant=NO_GEOMETRY_FUSION,
            expected_seed=seed,
            device=device,
        )
        raw, raw_metadata = _load_raw_efficientnet(
            Path(raw_root) / f"seed_{seed}/terminal.pt",
            expected_seed=seed,
            device=device,
        )
        _require(
            full_metadata["source_seed"] == no_geometry_metadata["source_seed"],
            "GeoPRR source seed differs across variants",
        )
        models[seed] = {
            FULL_MODEL: full,
            NO_GEOMETRY_MODEL: no_geometry,
            RAW_EFFICIENTNET_MODEL: raw,
        }
        model_metadata[str(seed)] = {
            FULL_MODEL: full_metadata,
            NO_GEOMETRY_MODEL: no_geometry_metadata,
            RAW_EFFICIENTNET_MODEL: raw_metadata,
        }

    autocast_enabled = device.type == "cuda" and bool(use_amp)
    autocast_dtype = (
        torch.bfloat16
        if device.type == "cuda" and torch.cuda.is_bf16_supported()
        else torch.float16
    )
    started = time.perf_counter()
    angle_metadata: dict[str, Any] = {}
    with _CompressedCsvWriter(output) as writer, torch.inference_mode():
        for angle_index, angle in enumerate(ANGLES):
            angle_started = time.perf_counter()
            dataset = PerspectiveAngleDataset(
                ordered_manifest,
                targets,
                angle=angle,
            )
            loader = _loader(
                dataset,
                batch_size=batch_size,
                shuffle=False,
                workers=workers,
                seed=EVALUATION_SEED + angle_index,
                cuda=device.type == "cuda",
            )
            observed_ids: list[str] = []
            available_rows = 0
            fallback_rows = 0
            for raw_batch in loader:
                raw = raw_batch["original_view"].to(
                    device, non_blocking=device.type == "cuda"
                )
                normalized = raw_batch["sarn_view"].to(
                    device, non_blocking=device.type == "cuda"
                )
                support = raw_batch["sarn_support_mask"].to(
                    device, non_blocking=device.type == "cuda"
                )
                active = raw_batch["sarn_active"].to(
                    device, non_blocking=device.type == "cuda"
                ).bool()
                homography = raw_batch["raw_to_sarn_homography"].to(
                    device, non_blocking=device.type == "cuda"
                )
                target = raw_batch["target"].float()
                predictions: dict[int, dict[str, torch.Tensor]] = {}
                for seed in SEEDS:
                    with torch.autocast(
                        device_type=device.type,
                        dtype=autocast_dtype,
                        enabled=autocast_enabled,
                    ):
                        full_output = models[seed][FULL_MODEL](
                            raw,
                            normalized,
                            support,
                            sarn_active=active,
                            raw_to_sarn_homography=homography,
                        )
                        no_geometry_output = models[seed][NO_GEOMETRY_MODEL](
                            raw,
                            normalized,
                            support,
                            sarn_active=active,
                            raw_to_sarn_homography=homography,
                        )
                        raw_output = models[seed][RAW_EFFICIENTNET_MODEL](raw)
                    predictions[seed] = {
                        FULL_MODEL: full_output["mean"].float().cpu(),
                        NO_GEOMETRY_MODEL: no_geometry_output["mean"].float().cpu(),
                        RAW_EFFICIENTNET_MODEL: raw_output.float().cpu(),
                    }

                ids = tuple(str(value) for value in raw_batch["sample_id"])
                scenes = tuple(str(value) for value in raw_batch["scene_stem"])
                axes = tuple(str(value) for value in raw_batch["perspective_axis"])
                reasons = tuple(str(value) for value in raw_batch["fallback_reason"])
                signs = raw_batch["perspective_sign"].cpu().tolist()
                availability = raw_batch["sarn_active"].cpu().bool().tolist()
                fallback = raw_batch["fallback"].cpu().bool().tolist()
                support_fraction = (
                    raw_batch["valid_support_fraction"].float().cpu().tolist()
                )
                target_values = target.cpu().tolist()
                observed_ids.extend(ids)
                available_rows += sum(bool(value) for value in availability)
                fallback_rows += sum(bool(value) for value in fallback)
                for seed in SEEDS:
                    for model_name in MODELS:
                        values = predictions[seed][model_name].tolist()
                        _require(len(values) == len(ids), "prediction batch length differs")
                        for row_index, prediction in enumerate(values):
                            scalar = float(prediction)
                            expected_target, expected_scene = targets[ids[row_index]]
                            _require(
                                scenes[row_index] == expected_scene,
                                "perspective scene differs",
                            )
                            _require(
                                abs(float(target_values[row_index]) - expected_target)
                                <= 1e-6,
                                "perspective target differs",
                            )
                            _require(
                                math.isfinite(scalar) and 0.0 <= scalar <= 1.0,
                                "perspective prediction is invalid",
                            )
                            _require(
                                bool(availability[row_index])
                                != bool(fallback[row_index]),
                                "availability and fallback are not complementary",
                            )
                            writer.write(
                                {
                                    "model": model_name,
                                    "seed": seed,
                                    "scene_id": scenes[row_index],
                                    "image_id": ids[row_index],
                                    "angle": angle,
                                    "target": expected_target,
                                    "prediction": scalar,
                                    "absolute_error": abs(scalar - expected_target),
                                    "availability": bool(availability[row_index]),
                                    "fallback": bool(fallback[row_index]),
                                    "valid_support_fraction": float(
                                        support_fraction[row_index]
                                    ),
                                    "fallback_reason": reasons[row_index],
                                    "perspective_axis": axes[row_index],
                                    "perspective_sign": int(signs[row_index]),
                                }
                            )
            _require(
                tuple(observed_ids) == tuple(ordered_ids),
                f"perspective roster order differs at {angle} degrees",
            )
            _require(
                available_rows + fallback_rows == len(ordered_ids),
                "perspective availability denominator differs",
            )
            angle_metadata[str(angle)] = {
                "samples": len(ordered_ids),
                "availability": available_rows,
                "fallback": fallback_rows,
                "elapsed_seconds": time.perf_counter() - angle_started,
            }
            print(
                json.dumps(
                    {
                        "angle": angle,
                        **angle_metadata[str(angle)],
                        "rows_written": writer.rows,
                    },
                    sort_keys=True,
                ),
                flush=True,
            )
        rows_written = writer.rows

    expected_rows = len(ANGLES) * len(SEEDS) * len(MODELS) * len(ordered_ids)
    _require(rows_written == expected_rows, "perspective Cartesian row count differs")
    metadata = {
        "schema_version": 1,
        "protocol": PROTOCOL,
        "status": "complete",
        "scope": {
            "formal_syncg_scene_holdout": True,
            "training_or_adaptation_during_evaluation": False,
            "all_high_angle_rows_retained": True,
            "same_pixels_for_every_model_and_seed": True,
            "deterministic_axis_and_sign_rule": (
                "robustness_degradations._sample_orientation with formal seed"
            ),
            "formal_25_and_45_degree_geometry": True,
            "inference_precision": (
                str(autocast_dtype).removeprefix("torch.")
                if autocast_enabled
                else "float32"
            ),
        },
        "data": {
            "samples": len(ordered_ids),
            "scenes": len({scene for _target, scene in targets.values()}),
            "angles": list(ANGLES),
            "models": list(MODELS),
            "seeds": list(SEEDS),
            "rows": rows_written,
            "robustness_seed": ROBUSTNESS_SEED,
        },
        "angle_input_diagnostics": angle_metadata,
        "models": model_metadata,
        "output": str(output),
        "elapsed_seconds": time.perf_counter() - started,
    }
    metadata_output.parent.mkdir(parents=True, exist_ok=True)
    metadata_output.write_text(
        json.dumps(
            metadata,
            ensure_ascii=False,
            allow_nan=False,
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return metadata


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--geoprr-root", type=Path, default=DEFAULT_GEOPRR_ROOT)
    parser.add_argument("--raw-root", type=Path, default=DEFAULT_RAW_ROOT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--reference", type=Path, default=DEFAULT_REFERENCE)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--metadata", type=Path)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--amp", action="store_true")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_argument_parser().parse_args(argv)
    metadata_path = args.metadata or Path(str(Path(args.output)) + ".metadata.json")
    result = evaluate_perspective_scan(
        geoprr_root=args.geoprr_root,
        raw_root=args.raw_root,
        manifest_path=args.manifest,
        reference_path=args.reference,
        output_path=args.output,
        metadata_path=metadata_path,
        device_name=args.device,
        workers=args.workers,
        batch_size=args.batch_size,
        use_amp=args.amp,
    )
    print(
        json.dumps(
            {
                "status": result["status"],
                "output": str(Path(args.output).resolve()),
                "metadata": str(Path(metadata_path).resolve()),
                "rows": result["data"]["rows"],
                "elapsed_seconds": result["elapsed_seconds"],
            },
            sort_keys=True,
        ),
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())



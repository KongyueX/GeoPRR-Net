def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def validate_external_reference(reference: Mapping[str, Any]) -> dict[str, Any]:
    """Validate the provenance needed for a paired SARN-v2 comparison.

    A row roster and model label cannot detect a swapped Raw ledger or pixels
    regenerated by a different OpenCV/SARN runtime.  Git state, filenames,
    seed fields, JSON types, and ordinary prediction tests also remain valid in
    those failure cases.  The reference therefore has to carry the established
    pairing protocol and exact SARN-v2 bindings; per-row pixel equality is
    checked against the freshly materialized evaluation batch below.
    """

    _require(
        reference.get("protocol") == REFERENCE_PROTOCOL,
        "METT external reference protocol is not the paired SyncG protocol",
    )
    _require(
        reference.get("status") == "complete",
        "METT external reference is incomplete",
    )
    bindings = reference.get("external_prediction_bindings")
    _require(
        isinstance(bindings, Mapping)
        and set(bindings) == set(EXTERNAL_DISPLAY_NAMES),
        "METT external reference model bindings differ",
    )
    verified: dict[str, list[dict[str, Any]]] = {}
    for model in EXTERNAL_DISPLAY_NAMES:
        model_bindings = bindings.get(model)
        _require(
            isinstance(model_bindings, list)
            and len(model_bindings) == len(REFERENCE_SEEDS)
            and all(isinstance(binding, Mapping) for binding in model_bindings),
            f"METT external reference bindings are incomplete: {model}",
        )
        by_seed = {int(binding["seed"]): binding for binding in model_bindings}
        _require(
            tuple(sorted(by_seed)) == REFERENCE_SEEDS
            and len(by_seed) == len(model_bindings),
            f"METT external reference seed roster differs: {model}",
        )
        verified[model] = []
        for seed in REFERENCE_SEEDS:
            binding = by_seed[seed]
            expected_method = f"SARN-v2+{model}_seed_{seed}"
            _require(
                binding.get("method") == expected_method
                and bool(str(binding.get("predictions", "")).strip())
                and bool(str(binding.get("sarn_sidecar", "")).strip()),
                f"METT external reference is not bound to SARN-v2: {model}/{seed}",
            )
            verified[model].append(dict(binding))
    return {
        "validated": True,
        "reference_protocol": REFERENCE_PROTOCOL,
        "reference_status": "complete",
        "external_prediction_bindings": verified,
        "row_pairing": {
            "condition_pixels": "exact condition_pixel_sha256 equality",
            "sarn_pixels": "exact sarn_pixel_sha256 equality",
        },
    }


def validate_external_reference_row(
    row: Mapping[str, Any], *, key: tuple[str, str]
) -> None:
    """Reject incomplete or internally inconsistent three-seed row vectors."""

    target = float(row.get("normalized_target"))
    _require(math.isfinite(target) and 0.0 <= target <= 1.0, f"invalid target: {key}")
    external = row.get("external")
    _require(
        isinstance(external, Mapping)
        and set(external) == set(EXTERNAL_DISPLAY_NAMES),
        f"external reference model roster differs: {key}",
    )
    for model in EXTERNAL_DISPLAY_NAMES:
        block = external.get(model)
        _require(isinstance(block, Mapping), f"external model row is missing: {model}/{key}")
        seeds = tuple(int(value) for value in block.get("seeds", ()))
        predictions = block.get("predictions")
        passed = block.get("passed")
        errors = block.get("absolute_errors")
        _require(
            seeds == REFERENCE_SEEDS
            and isinstance(predictions, list)
            and isinstance(passed, list)
            and isinstance(errors, list)
            and len(predictions) == len(passed) == len(errors) == len(REFERENCE_SEEDS)
            and all(isinstance(value, bool) for value in passed),
            f"external three-seed vectors differ: {model}/{key}",
        )
        for seed, prediction, success, error_value in zip(
            seeds, predictions, passed, errors, strict=True
        ):
            error = float(error_value)
            _require(
                math.isfinite(error) and 0.0 <= error <= 1.0,
                f"external error is invalid: {model}/{seed}/{key}",
            )
            if success:
                value = float(prediction)
                _require(
                    math.isfinite(value)
                    and 0.0 <= value <= 1.0
                    and abs(error - abs(value - target)) <= 2.0e-6,
                    f"external prediction/error differs: {model}/{seed}/{key}",
                )
            else:
                _require(
                    prediction is None and error == 1.0,
                    f"external failure encoding differs: {model}/{seed}/{key}",
                )


def apply_evaluation_sensitivity_overrides(
    anchor: torch.nn.Module,
    correction: torch.nn.Module,
    *,
    posterior_scale: float | None,
    residual_scale: float | None,
) -> dict[str, float]:
    """Apply inference-only scale perturbations for sensitivity analysis."""

    applied: dict[str, float] = {}
    if posterior_scale is not None:
        value = float(posterior_scale)
        _require(
            math.isfinite(value)
            and MIN_POSTERIOR_SCALE <= value <= MAX_POSTERIOR_SCALE,
            "METT posterior-scale override is out of range",
        )
        head = getattr(anchor, "raw_posterior_head", None)
        projection = getattr(head, "log_scale_projection", None)
        _require(
            isinstance(projection, torch.nn.Linear)
            and projection.out_features == 1,
            "METT posterior-scale head is unavailable",
        )
        with torch.no_grad():
            projection.weight.zero_()
            projection.bias.fill_(math.log(value))
        applied["posterior_scale"] = value
    if residual_scale is not None:
        value = float(residual_scale)
        _require(
            math.isfinite(value) and 0.0 <= value <= 1.0,
            "METT residual-scale override is out of range",
        )
        bridge = getattr(correction, "natural_parameter_bridge", None)
        _require(
            bridge is not None and hasattr(bridge, "learned_residual_scale"),
            "METT residual bridge is unavailable",
        )
        bridge.learned_residual_scale = value
        applied["residual_scale"] = value
    return applied


def _metrics(errors: Sequence[float]) -> dict[str, float]:
    values = np.asarray(tuple(float(value) for value in errors), dtype=np.float64)
    _require(values.ndim == 1 and values.size > 0, "METT metric rows are empty")
    _require(bool(np.isfinite(values).all()), "METT metric errors are non-finite")
    return {
        "nmae": float(values.mean()),
        "rmse": float(np.sqrt(np.mean(values**2))),
        "p95_absolute_error": float(np.quantile(values, 0.95)),
        "p99_absolute_error": float(np.quantile(values, 0.99)),
        "maximum_absolute_error": float(values.max()),
        "acc_at_1_percent": float(np.mean(values <= 0.01)),
        "acc_at_2_percent": float(np.mean(values <= 0.02)),
        "acc_at_5_percent": float(np.mean(values <= 0.05)),
    }


def posterior_batch_diagnostics(
    posterior: torch.Tensor,
    target: torch.Tensor,
) -> dict[str, torch.Tensor]:
    """Return proper scores and central-interval diagnostics per row."""

    _require(
        posterior.ndim == 2
        and target.shape == (posterior.shape[0],)
        and posterior.shape[1] >= 16,
        "METT posterior diagnostic shapes differ",
    )
    probability = posterior.detach().float().cpu()
    truth = target.detach().float().cpu().clamp(0.0, 1.0)
    _require(
        bool(torch.isfinite(probability).all())
        and bool((probability >= 0.0).all()),
        "METT posterior diagnostic contains invalid mass",
    )
    probability = probability / probability.sum(dim=1, keepdim=True).clamp_min(
        1.0e-12
    )
    bins = int(probability.shape[1])
    grid = torch.linspace(0.0, 1.0, bins, dtype=torch.float32)
    cdf = probability.cumsum(dim=1)
    observation_cdf = (grid[None, :] >= truth[:, None]).float()
    crps = ((cdf - observation_cdf).square()).sum(dim=1) / float(bins - 1)

    position = truth * float(bins - 1)
    lower_index = position.floor().long().clamp(0, bins - 1)
    upper_index = position.ceil().long().clamp(0, bins - 1)
    upper_weight = position - lower_index.float()
    lower_weight = 1.0 - upper_weight
    lower_mass = probability.gather(1, lower_index[:, None]).squeeze(1)
    upper_mass = probability.gather(1, upper_index[:, None]).squeeze(1)
    two_hot_nll = -(
        lower_weight * lower_mass.clamp_min(1.0e-12).log()
        + upper_weight * upper_mass.clamp_min(1.0e-12).log()
    )

    lower_cdf = cdf.gather(1, lower_index[:, None]).squeeze(1)
    upper_cdf = cdf.gather(1, upper_index[:, None]).squeeze(1)
    pit = lower_cdf + upper_weight * (upper_cdf - lower_cdf)
    mean = (probability * grid[None, :]).sum(dim=1)
    variance = (
        probability * (grid[None, :] - mean[:, None]).square()
    ).sum(dim=1)
    result: dict[str, torch.Tensor] = {
        "crps": crps,
        "two_hot_nll": two_hot_nll,
        "pit": pit.clamp(0.0, 1.0),
        "variance": variance,
    }
    for level in INTERVAL_LEVELS:
        tail = (1.0 - level) / 2.0
        lower_quantile = torch.full(
            (probability.shape[0], 1), tail, dtype=torch.float32
        )
        upper_quantile = torch.full(
            (probability.shape[0], 1), 1.0 - tail, dtype=torch.float32
        )
        lower_bin = torch.searchsorted(cdf.contiguous(), lower_quantile).squeeze(1)
        upper_bin = torch.searchsorted(cdf.contiguous(), upper_quantile).squeeze(1)
        lower_bound = grid[lower_bin.clamp(0, bins - 1)]
        upper_bound = grid[upper_bin.clamp(0, bins - 1)]
        suffix = str(int(round(level * 100)))
        result[f"coverage_{suffix}"] = (
            (truth >= lower_bound) & (truth <= upper_bound)
        )
        result[f"width_{suffix}"] = upper_bound - lower_bound
    return result


def _posterior_summary(
    rows: Sequence[Mapping[str, Any]],
    *,
    method: str,
) -> dict[str, Any]:
    diagnostics = [row[method]["posterior"] for row in rows]
    result: dict[str, Any] = {
        "mean_crps": statistics.fmean(float(row["crps"]) for row in diagnostics),
        "mean_two_hot_nll": statistics.fmean(
            float(row["two_hot_nll"]) for row in diagnostics
        ),
        "mean_variance": statistics.fmean(
            float(row["variance"]) for row in diagnostics
        ),
    }
    calibration_errors = []
    for level in INTERVAL_LEVELS:
        suffix = str(int(round(level * 100)))
        coverage = statistics.fmean(
            float(bool(row[f"coverage_{suffix}"])) for row in diagnostics
        )
        result[f"empirical_coverage_{suffix}"] = coverage
        result[f"mean_interval_width_{suffix}"] = statistics.fmean(
            float(row[f"width_{suffix}"]) for row in diagnostics
        )
        calibration_errors.append(abs(coverage - level))
    result["mean_absolute_interval_calibration_error"] = statistics.fmean(
        calibration_errors
    )
    pit = np.asarray([float(row["pit"]) for row in diagnostics], dtype=np.float64)
    thresholds = np.linspace(0.1, 0.9, 9)
    result["pit_cdf_calibration_mae"] = float(
        np.mean([abs(float(np.mean(pit <= value)) - value) for value in thresholds])
    )
    variances = np.asarray(
        [float(row["variance"]) for row in diagnostics], dtype=np.float64
    )
    errors = np.asarray(
        [float(row[method]["absolute_error"]) for row in rows], dtype=np.float64
    )
    if float(np.std(variances)) > 0.0 and float(np.std(errors)) > 0.0:
        result["variance_absolute_error_pearson"] = float(
            np.corrcoef(variances, errors)[0, 1]
        )
    else:
        result["variance_absolute_error_pearson"] = 0.0
    return result


def _summarize(
    rows: Sequence[Mapping[str, Any]],
) -> dict[str, Any]:
    condition_sets = {
        **{condition: (condition,) for condition in CONDITIONS},
        "projective_pooled": PROJECTIVE_CONDITIONS,
        "all_conditions": CONDITIONS,
    }
    summary: dict[str, Any] = {}
    for label, selected in condition_sets.items():
        subset = [row for row in rows if str(row["condition"]) in selected]
        _require(bool(subset), f"METT summary arm is empty: {label}")
        candidate = {
            method: _metrics(
                [float(row[method]["absolute_error"]) for row in subset]
            )
            for method in ("raw_anchor", "sarn_endpoint", "tangent_base", "mett")
        }
        posterior = {
            method: _posterior_summary(subset, method=method)
            for method in POSTERIOR_METHODS
        }
        external: dict[str, Any] = {}
        for reference_name, display_name in EXTERNAL_DISPLAY_NAMES.items():
            seed_count = len(
                subset[0]["external"][reference_name]["absolute_errors"]
            )
            per_seed = []
            for seed_index in range(seed_count):
                per_seed.append(
                    _metrics(
                        [
                            float(
                                row["external"][reference_name]
                                ["absolute_errors"][seed_index]
                            )
                            for row in subset
                        ]
                    )
                )
            metric_names = tuple(per_seed[0])
            mean_across_seeds = {
                name: statistics.fmean(seed[name] for seed in per_seed)
                for name in metric_names
            }
            external[display_name] = {
                "per_seed": per_seed,
                "mean_across_seeds": mean_across_seeds,
                "mett_minus_external_seed_mean_nmae": (
                    candidate["mett"]["nmae"] - mean_across_seeds["nmae"]
                ),
            }
        summary[label] = {
            "conditions": list(selected),
            "rows": len(subset),
            "scenes": len({str(row["scene_stem"]) for row in subset}),
            "candidate": candidate,
            "posterior": posterior,
            "external_models": external,
            "relation_available_fraction": statistics.fmean(
                float(bool(row["relation_available"])) for row in subset
            ),
            "mett_minus_sarn_endpoint_nmae": (
                candidate["mett"]["nmae"] - candidate["sarn_endpoint"]["nmae"]
            ),
            "mett_negative_transfer_fraction_vs_sarn_endpoint": statistics.fmean(
                float(row["mett"]["absolute_error"] > row["sarn_endpoint"]["absolute_error"])
                for row in subset
            ),
            "mett_improvement_fraction_vs_sarn_endpoint": statistics.fmean(
                float(row["mett"]["absolute_error"] < row["sarn_endpoint"]["absolute_error"])
                for row in subset
            ),
            "macro_scene_nmae": {
                method: statistics.fmean(
                    statistics.fmean(
                        float(row[method]["absolute_error"])
                        for row in subset
                        if str(row["scene_stem"]) == scene
                    )
                    for scene in sorted({str(row["scene_stem"]) for row in subset})
                )
                for method in ("raw_anchor", "sarn_endpoint", "mett")
            },
        }
    return summary


def evaluate_mett(
    *,
    manifest_path: Path,
    reference_path: Path,
    output_path: Path,
    checkpoint_path: Path | None = None,
    direct_checkpoint_path: Path = DEFAULT_DIRECT_CHECKPOINT,
    device_name: str = "cuda:0",
    workers: int = 4,
    batch_size: int = 64,
    use_amp: bool = False,
    posterior_scale_override: float | None = None,
    residual_scale_override: float | None = None,
    allow_zero_initialized_control: bool = False,
    expected_variant: str = "full",
    trained_checkpoint_loader: Callable[..., tuple[torch.nn.Module, torch.nn.Module, dict[str, Any]]] = load_mett_models,
    trained_checkpoint_validator: Callable[..., dict[str, Any]] | None = validate_mett_variant_metadata,
    publication_identity_resolver: Callable[[str], dict[str, str]] = publication_model_identity,
    evaluation_protocol: str = PROTOCOL,
) -> dict[str, Any]:
    _require(workers >= 0 and batch_size >= 1, "METT evaluation sizes differ")
    _require(expected_variant in METT_VARIANTS, "unknown METT experiment variant")
    _require(bool(evaluation_protocol.strip()), "evaluation protocol is empty")
    _require(
        (checkpoint_path is None) == bool(allow_zero_initialized_control),
        "select exactly one trained checkpoint or the explicit zero-initialized control",
    )
    _require(
        checkpoint_path is not None
        or (posterior_scale_override is None and residual_scale_override is None),
        "sensitivity overrides require a trained METT checkpoint",
    )
    output = Path(output_path).resolve()
    _require(not output.exists(), f"METT evaluation output exists: {output}")
    reference_source = Path(reference_path).resolve()
    _require(reference_source.is_file(), "METT reference evaluation is missing")
    reference = json.loads(reference_source.read_text(encoding="utf-8-sig"))
    _require(isinstance(reference, Mapping), "METT reference is not an object")
    external_comparator_evidence = validate_external_reference(reference)
    reference_rows = reference.get("per_sample_condition")
    _require(
        isinstance(reference_rows, list) and bool(reference_rows),
        "METT reference rows are missing",
    )
    reference_by_key: dict[tuple[str, str], Mapping[str, Any]] = {}
    for index, row in enumerate(reference_rows):
        _require(isinstance(row, Mapping), f"METT reference row {index} is invalid")
        key = (str(row["sample_id"]), str(row["condition"]))
        _require(key not in reference_by_key, "METT reference row keys repeat")
        for digest_name in ("condition_pixel_sha256", "sarn_pixel_sha256"):
            digest = str(row.get(digest_name, ""))
            _require(
                len(digest) == 64
                and all(character in "0123456789abcdef" for character in digest),
                f"METT reference pixel digest is invalid: {digest_name}/{key}",
            )
        validate_external_reference_row(row, key=key)
        reference_by_key[key] = row
    _require(
        len(reference_by_key) == len(reference_rows),
        "METT reference row keys repeat",
    )
    ordered_ids = tuple(
        dict.fromkeys(str(row["sample_id"]) for row in reference_rows)
    )
    targets: dict[str, tuple[float, str]] = {}
    for row in reference_rows:
        sample_id = str(row["sample_id"])
        value = (float(row["normalized_target"]), str(row["scene_stem"]))
        if sample_id in targets:
            _require(targets[sample_id] == value, "METT reference target differs")
        else:
            targets[sample_id] = value

    manifest_rows = load_manifest(manifest_path)
    manifest_by_id = {row.sample_id: row for row in manifest_rows}
    _require(
        set(ordered_ids) == set(manifest_by_id),
        "METT manifest and reference rosters differ",
    )
    ordered_manifest = tuple(manifest_by_id[sample_id] for sample_id in ordered_ids)

    device = torch.device(device_name)
    if device.type == "cuda":
        _require(torch.cuda.is_available(), "CUDA is unavailable")
    torch.manual_seed(20260818)
    if device.type == "cuda":
        torch.cuda.manual_seed_all(20260818)
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True

    if checkpoint_path is None:
        anchor, anchor_metadata = load_moment_exact_anchor_from_direct_checkpoint(
            direct_checkpoint_path, device=device
        )
        for parameter in anchor.parameters():
            parameter.requires_grad_(False)
        correction = A152METTCorrection().to(device).eval()
        model_metadata: dict[str, Any] = {
            "checkpoint": None,
            "state": "zero_initialized_endpoint_tangent_correction",
            "evaluation_label": "zero_initialized_control",
            "source_anchor": anchor_metadata,
        }
    else:
        anchor, correction, model_metadata = trained_checkpoint_loader(
            checkpoint_path, device=device
        )
        validated_variant_identity = (
            trained_checkpoint_validator(
                model_metadata, expected_variant=expected_variant
            )
            if trained_checkpoint_validator is not None
            else {"validation": "performed_by_trained_checkpoint_loader"}
        )
        model_metadata = {
            **model_metadata,
            "validated_mett_variant": validated_variant_identity,
        }
    anchor.eval()
    correction.eval()
    sensitivity_overrides = apply_evaluation_sensitivity_overrides(
        anchor,
        correction,
        posterior_scale=posterior_scale_override,
        residual_scale=residual_scale_override,
    )
    if sensitivity_overrides:
        _require(
            trained_checkpoint_validator is not None,
            "sensitivity overrides require a checkpoint metadata validator",
        )
        validated_base_identity = trained_checkpoint_validator(
            model_metadata, expected_variant=expected_variant
        )
        model_metadata = {
            **model_metadata,
            "inference_sensitivity_overrides": sensitivity_overrides,
            "validated_mett_variant_base": validated_base_identity,
        }
        if expected_variant == "full":
            model_metadata["validated_full_mett_base"] = validated_base_identity

    candidate_rows: list[dict[str, Any]] = []
    autocast_enabled = device.type == "cuda" and bool(use_amp)
    autocast_dtype = (
        torch.bfloat16
        if device.type == "cuda" and torch.cuda.is_bf16_supported()
        else torch.float16
    )
    with torch.inference_mode():
        for condition_index, condition in enumerate(CONDITIONS):
            dataset = _SharedPixelDataset(
                ordered_manifest, targets, condition=condition
            )
            loader = _loader(
                dataset,
                batch_size=batch_size,
                shuffle=False,
                workers=workers,
                seed=20260818 + condition_index,
                cuda=device.type == "cuda",
            )
            for raw_batch in loader:
                original = raw_batch["original_view"].to(device)
                sarn = raw_batch["sarn_view"].to(device)
                support = raw_batch["sarn_support_mask"].to(device)
                dataset_active = raw_batch["sarn_active"].to(device).bool()
                homography = raw_batch["raw_to_sarn_homography"].to(device)
                target = raw_batch["target"].float()
                effective_active = dataset_active & (condition != "clean")
                with torch.autocast(
                    device_type=device.type,
                    dtype=autocast_dtype,
                    enabled=autocast_enabled,
                ):
                    endpoints = frozen_twin_endpoint_forward(
                        anchor, original, sarn
                    )
                    prediction = forward_a15_correction(
                        correction,
                        {
                            "raw_posterior": endpoints["raw_posterior"],
                            "sarn_posterior": endpoints["sarn_posterior"],
                            "raw_mean": endpoints["raw_mean"],
                            "sarn_mean": endpoints["sarn_mean"],
                            "raw_features": endpoints["raw_features"],
                            "sarn_features": endpoints["sarn_features"],
                            "sarn_support_mask": support,
                            "sarn_active": effective_active,
                            "raw_to_sarn_homography": homography,
                        },
                        endpoint_null=False,
                    )
                values = {
                    "raw_anchor": prediction["raw_anchor_mean"].float().cpu(),
                    "sarn_endpoint": prediction["sarn_endpoint_mean"].float().cpu(),
                    "tangent_base": prediction["tangent_base_mean"].float().cpu(),
                    "mett": prediction["mean"].float().cpu(),
                }
                posterior_values = {
                    "raw_anchor": prediction["raw_anchor_posterior"],
                    "sarn_endpoint": prediction["sarn_endpoint_posterior"],
                    "mett": prediction["progress_posterior"],
                }
                posterior_diagnostics = {
                    method: posterior_batch_diagnostics(probability, target)
                    for method, probability in posterior_values.items()
                }
                relation = prediction["relation_available"].bool().cpu()
                ids = tuple(str(value) for value in raw_batch["sample_id"])
                scenes = tuple(str(value) for value in raw_batch["scene_stem"])
                condition_pixel_digests = tuple(
                    str(value) for value in raw_batch["condition_pixel_sha256"]
                )
                sarn_pixel_digests = tuple(
                    str(value) for value in raw_batch["sarn_pixel_sha256"]
                )
                _require(
                    len(ids)
                    == len(scenes)
                    == len(condition_pixel_digests)
                    == len(sarn_pixel_digests),
                    "METT regenerated pixel identity batch is misaligned",
                )
                for row_index, sample_id in enumerate(ids):
                    key = (sample_id, condition)
                    _require(key in reference_by_key, "METT reference key missing")
                    reference_row = reference_by_key[key]
                    expected_target = float(reference_row["normalized_target"])
                    observed_target = float(target[row_index])
                    _require(
                        abs(expected_target - observed_target) <= 1.0e-6,
                        "METT regenerated target differs",
                    )
                    _require(
                        condition_pixel_digests[row_index]
                        == reference_row["condition_pixel_sha256"],
                        f"METT/reference degraded pixels differ: {key}",
                    )
                    _require(
                        sarn_pixel_digests[row_index]
                        == reference_row["sarn_pixel_sha256"],
                        f"METT/reference SARN pixels differ: {key}",
                    )
                    row: dict[str, Any] = {
                        "sample_id": sample_id,
                        "scene_stem": scenes[row_index],
                        "condition": condition,
                        "normalized_target": expected_target,
                        "condition_pixel_sha256": condition_pixel_digests[row_index],
                        "sarn_pixel_sha256": sarn_pixel_digests[row_index],
                        "relation_available": bool(relation[row_index]),
                        "external": reference_row["external"],
                    }
                    for method, tensor in values.items():
                        scalar = float(tensor[row_index])
                        _require(
                            math.isfinite(scalar) and 0.0 <= scalar <= 1.0,
                            "METT prediction is invalid",
                        )
                        row[method] = {
                            "prediction": scalar,
                            "absolute_error": abs(scalar - expected_target),
                        }
                        if method in posterior_diagnostics:
                            row[method]["posterior"] = {
                                name: (
                                    bool(tensor[row_index])
                                    if tensor.dtype == torch.bool
                                    else float(tensor[row_index])
                                )
                                for name, tensor in posterior_diagnostics[method].items()
                            }
                    candidate_rows.append(row)

    expected_count = len(ordered_ids) * len(CONDITIONS)
    _require(
        len(candidate_rows) == expected_count,
        "METT evaluation Cartesian row count differs",
    )
    summary = _summarize(candidate_rows)
    paper_identity = (
        None
        if checkpoint_path is None
        else publication_identity_resolver(expected_variant)
    )
    result = {
        "schema_version": 1,
        "protocol": evaluation_protocol,
        "status": "complete",
        "scope": {
            "development_cohort": True,
            "historical_holdout_already_used": True,
            "training_or_adaptation_during_evaluation": False,
            "sample_router_or_external_prediction_fusion": False,
            "inference_sensitivity_analysis": bool(sensitivity_overrides),
            "experiment_variant": (
                "zero_initialized_control"
                if checkpoint_path is None
                else expected_variant
            ),
            "candidate_label": (
                "zero_initialized_control"
                if checkpoint_path is None
                else paper_identity["display_name"]
            ),
            "posterior_interpretation": (
                "fixed-scale heuristic posterior; proper scores and empirical "
                "coverage are diagnostics, not a learned-calibration claim"
            ),
            "external_comparator_semantics": (
                "reference row keys omit the preprocessing prefix; all three "
                "external model families are the bound SARN-v2 ledgers"
            ),
            "inference_precision": (
                str(autocast_dtype).removeprefix("torch.")
                if autocast_enabled
                else "float32"
            ),
        },
        "publication_model": paper_identity,
        "model": model_metadata,
        "external_comparator_evidence": external_comparator_evidence,
        "data": {
            "manifest": str(Path(manifest_path).resolve()),
            "reference": str(reference_source),
            "samples": len(ordered_ids),
            "conditions": list(CONDITIONS),
            "rows": len(candidate_rows),
        },
        "summary": summary,
        "per_sample_condition": candidate_rows,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(result, ensure_ascii=False, allow_nan=False, indent=2, sort_keys=True)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    for label in (*CONDITIONS, "projective_pooled", "all_conditions"):
        row = summary[label]
        print(
            json.dumps(
                {
                    "condition": label,
                    "mett_nmae": row["candidate"]["mett"]["nmae"],
                    "raw_nmae": row["candidate"]["raw_anchor"]["nmae"],
                    "sarn_nmae": row["candidate"]["sarn_endpoint"]["nmae"],
                    "sarn_v2_efficientnet_b0_seed_mean_nmae": row[
                        "external_models"
                    ]["SARN-v2+EfficientNet-B0"]["mean_across_seeds"]["nmae"],
                    "mett_minus_sarn_v2_efficientnet_b0": row[
                        "external_models"
                    ]["SARN-v2+EfficientNet-B0"]
                    ["mett_minus_external_seed_mean_nmae"],
                },
                sort_keys=True,
            ),
            flush=True,
        )
    return {
        "status": "complete",
        "output": str(output),
        "all_conditions": summary["all_conditions"],
        "projective_pooled": summary["projective_pooled"],
    }


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--reference", type=Path, default=DEFAULT_REFERENCE)
    parser.add_argument("--output", type=Path, required=True)
    candidate = parser.add_mutually_exclusive_group(required=True)
    candidate.add_argument("--checkpoint", type=Path)
    candidate.add_argument(
        "--zero-initialized-control",
        action="store_true",
        help="explicitly evaluate the untrained endpoint-tangent control",
    )
    parser.add_argument(
        "--direct-checkpoint", type=Path, default=DEFAULT_DIRECT_CHECKPOINT
    )
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument(
        "--experiment-variant", choices=tuple(METT_VARIANTS), default="full"
    )
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument(
        "--amp",
        action="store_true",
        help="use CUDA BF16/FP16 instead of the FP32 external-model setting",
    )
    parser.add_argument("--posterior-scale", type=float)
    parser.add_argument("--residual-scale", type=float)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_argument_parser().parse_args(argv)
    result = evaluate_mett(
        manifest_path=args.manifest,
        reference_path=args.reference,
        output_path=args.output,
        checkpoint_path=args.checkpoint,
        direct_checkpoint_path=args.direct_checkpoint,
        device_name=args.device,
        workers=args.workers,
        batch_size=args.batch_size,
        use_amp=args.amp,
        posterior_scale_override=args.posterior_scale,
        residual_scale_override=args.residual_scale,
        allow_zero_initialized_control=args.zero_initialized_control,
        expected_variant=args.experiment_variant,
    )
    print(json.dumps(result, ensure_ascii=False, allow_nan=False, sort_keys=True))
    return 0


